"""Verify catalog definitions against the local Go and Health Sync source trees."""
import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CATALOG = ROOT / "experiments/dbt_metrics/models/health_metric_catalog.yml"
SWIFT = ROOT.parent / "health-sync/health-sync/HealthKitManager.swift"


def named_block(source, header):
    return source.split(header, 1)[1].split("\n}", 1)[0]


def swift_ingress_source(ingress):
    def swift_string(value):
        return json.dumps(value, ensure_ascii=False)

    result = [
        "// Generated by Health Processing check_semantic_catalog.py --write-swift-ingress.",
        "",
        "nonisolated enum HealthKitIngress {",
        "    struct Quantity: Sendable {",
        "        let name: String",
        "        let unit: String",
        "        let hourlySum: Bool",
        "    }",
        "",
        "    static let quantities: [String: Quantity] = [",
    ]
    for identifier, row in sorted(ingress["quantities"].items()):
        if grain := row.get("live_grain"):
            name, unit = swift_string(row["key"]), swift_string(row["unit"])
            hourly = str(grain == "hour_sum").lower()
            result.append(f"        {swift_string(identifier)}: .init(name: {name}, unit: {unit}, hourlySum: {hourly}),")
    result += [
        "    ]", "",
        "    static let liveGrains: [String: String] = quantities.values.reduce(into: [:]) { result, quantity in",
        '        result[quantity.name] = quantity.hourlySum ? "hour_sum" : "sample_start"',
        "    }", "",
        "    static let categoryEvents: [CategoryEventDef] = [",
    ]
    for identifier, row in ingress["categories"].items():
        if row["mode"] in {"count", "duration_minutes"}:
            kind = "count" if row["mode"] == "count" else "durationMinutes"
            result.append(f"        .init(identifierRaw: {swift_string(identifier)}, name: {swift_string(row['key'])}, kind: .{kind}),")
    return "\n".join(result + ["    ]", "}", ""])


def observation_evidence(swift_path, ingress):
    swift = swift_path.read_text()
    ui = (ROOT / "internal/ui/metrics_page.go").read_text()
    policy = (ROOT / "internal/storage/aggregation_policy.go").read_text()
    quality = (ROOT / "internal/health/quality.go").read_text()
    result = {}

    def record(key, field, value):
        result.setdefault(key, {})[field] = value

    for identifier, row in ingress["quantities"].items():
        if "xml_legacy_key" in row:
            suffix = row.get("legacy_identifiers", [identifier])[-1].split("Identifier", 1)[1]
            record(row["xml_legacy_key"], "xml", [suffix, row.get("xml_default_unit", row["unit"])])
    for row in ingress["categories"].values():
        if row["mode"] == "sleep_stages":
            for value, key in row["values"].items():
                result.setdefault(key, {}).setdefault("xml_categories", []).append(value)
            record(row["key"], "xml_special_unit", row["unit"])
        elif row["mode"] in {"stand_hour", "duration_minutes"}:
            record(row["key"], "xml_special_unit", row["unit"])
    generated = swift_path.with_name("HealthKitIngress.generated.swift")
    if generated.is_file():
        if generated.read_text() != swift_ingress_source(ingress):
            raise ValueError("stale Health Sync ingress source; refresh from the semantic catalog")
        identifiers = re.findall(r"\.init\(identifier: \.(\w+),\s*unit: ", swift)
        expected_quantities = {row["key"] for row in ingress["quantities"].values() if row.get("live_grain")}
        expected_symbols = {key: row[0] for key, row in live_ingress_evidence(ingress).items() if key in expected_quantities}
        if Counter(identifiers) != Counter(expected_symbols.values()):
            raise ValueError("Swift HealthKit query definitions do not match the generated quantity catalog")
        for key, metadata in live_ingress_evidence(ingress).items():
            record(key, "ios", metadata)
    else:
        for hk, key, unit, is_sum in re.findall(
            r'\.init\(identifier: \.(\w+),\s*name: "(\w+)",\s*unit: [^\n]+\s*serverUnits: "([^"]+)", isSUM: (true|false)', swift
        ):
            record(key, "ios", [hk, unit, "hour_sum" if is_sum == "true" else "sample_start"])
        for hk, key, kind in re.findall(r'identifierRaw: HKCategoryTypeIdentifier\.(\w+)\.rawValue,\s*name: "(\w+)", kind: \.(\w+)', swift):
            record(key, "ios", [hk, "min" if kind == "durationMinutes" else "count", "event_start"])
    for key, unit in re.findall(r'MetricData\(name: "(\w+)",\s*units: "([^"]+)"', swift):
        if key != "sleep_analysis":
            record(key, "ios", ["sleepAnalysis", unit, "wake_date" if key in {"night_sleep_total", "nap_total"} else "stage_start"])
    declared_ios = set(re.findall(r'\bname: "([a-z0-9_]+)"', swift)) - {"sleep_analysis"}
    if not generated.is_file() and declared_ios != {k for k, v in result.items() if "ios" in v}:
        raise ValueError("unparsed iOS definition: " + str(declared_ios - {k for k,v in result.items() if "ios" in v}))
    for group, keys in re.findall(r'"(\w+)", \[\]string\{([^}]+)\}', ui.split("var categories =", 1)[1].split("\n}\n", 1)[0]):
        for key in re.findall(r'"(\w+)"', keys):
            record(key, "ui_group", group)
    for key in re.findall(r'"(\w+)"', policy.split('metrics := []string{', 1)[1].split('}', 1)[0]):
        record(key, "bucket_sum", True)
    for column, key in re.findall(r'column: "(\w+)", metric: "(\w+)"', policy):
        record(key, "daily_column", column)
    for key, low, high in re.findall(r'"(\w+)":\s*\{Min: ([\d.]+), Max: ([\d.]+)\}', quality):
        record(key, "inclusive_range", [float(low), float(high)])
    if not all(any(field in row for row in result.values()) for field in ("xml","ios","bucket_sum","ui_group","daily_column","inclusive_range")):
        raise ValueError("one or more source registries could not be parsed")
    return result


def go_fields(owner, name):
    block = named_block((ROOT / owner).read_text(), f"type {name} struct {{")
    return set(re.findall(r'^[ \t]*([A-Z]\w*)[ \t]+[^\s/]', block, re.MULTILINE))


def source_units(row):
    units = set()
    if "xml" in row:
        units.add(row["xml"][1])
    if "ios" in row:
        units.add(row["ios"][1])
    if "xml_categories" in row:
        units.add("hr")
    if "xml_special_unit" in row:
        units.add(row["xml_special_unit"])
    return sorted(units)


def unique_pairs(pairs):
    output = {}
    for key, value in pairs:
        if key in output:
            raise ValueError(f"duplicate catalog key: {key}")
        output[key] = value
    return output


def definitions(catalog):
    ingress = catalog["healthkit_ingress"]
    ingress_by_key = {}
    for identifier, rule in sorted((ingress["quantities"] | ingress["categories"]).items()):
        if "key" in rule:
            ingress_by_key.setdefault(rule["key"], []).append(rule | {"identifier": identifier})
    for key, row in catalog["observations"].items():
        units = source_units(row)
        yield dict(catalog["observation_defaults"], metric_id=key,
                   source_keys=[key], units=units or ["unknown"], evidence=row,
                   healthkit_ingress=ingress_by_key.get(key, []),
                   quality=row.get("inclusive_range", "no named range; retain source quality"),
                   consumers=["Metrics"] if "ui_group" in row else ["unverified"],
                   method="channel-dependent; see adapter evidence",
                   provenance="named adapter" if units else "producer unconfirmed")
    for family, group in catalog["families"].items():
        shared = {k:v for k,v in group.items() if k not in {"fields","ignored_fields","go_type"}}
        for key, field in group["fields"].items():
            yield catalog["derived_defaults"] | shared | field | {"metric_id": family + "." + key}
    for key, row in catalog["contracts"].items():
        yield catalog["derived_defaults"] | row | {"metric_id":key}


def live_ingress_evidence(ingress):
    live = {}
    for group in ("quantities", "categories"):
        for identifier, row in ingress[group].items():
            if row.get("live_grain") or row.get("mode") in {"count", "duration_minutes"}:
                suffix = identifier.split("Identifier", 1)[1]
                swift_identifier = {"VO2Max": "vo2Max", "UVExposure": "uvExposure"}.get(suffix, suffix[:1].lower() + suffix[1:])
                live[row["key"]] = [swift_identifier, row["unit"], row.get("live_grain", "event_start")]
    return live


def validate_ingress(ingress, observations):
    if ingress["version"] != 1:
        raise ValueError("unsupported HealthKit ingress version")
    seen = set(ingress["quantities"]) | set(ingress["categories"])
    units = {}
    for field, prefix in (("quantities", "HKQuantityTypeIdentifier"), ("categories", "HKCategoryTypeIdentifier")):
        for identifier, row in ingress[field].items():
            if not identifier.startswith(prefix):
                raise ValueError(f"invalid HealthKit identifier: {identifier}")
            for legacy in row.get("legacy_identifiers", []):
                if not legacy.startswith(prefix) or legacy in seen:
                    raise ValueError(f"duplicate or invalid legacy HealthKit identifier: {legacy}")
                seen.add(legacy)
            if row.get("mode") == "skip":
                continue
            key = row["key"]
            if key in units:
                raise ValueError(f"duplicate ingress key: {key}")
            units[key] = row["unit"]
            if row.get("xml_requires_unit") and "xml_default_unit" in row:
                raise ValueError(f"conflicting missing-unit policy: {key}")
            if field == "quantities" and "live_grain" in row and row["live_grain"] not in {"hour_sum", "sample_start"}:
                raise ValueError(f"unsupported live quantity grain: {key}")
            if row.get("separate_archive_samples") and row.get("live_grain") != "hour_sum":
                raise ValueError(f"archive grain separation requires an hourly live total: {key}")
            if row.get("archive_scale_requires_revision") and (row["unit"] != "%" or not row.get("xml_fraction_to_percent")):
                raise ValueError(f"revision-sensitive percentages must declare the XML scale: {key}")
    expected = {key: row["ios"] for key, row in observations.items() if "ios" in row and row["ios"][0] != "sleepAnalysis"}
    live = live_ingress_evidence(ingress)
    if live != expected:
        raise ValueError(f"HealthKit live contract drift: {sorted(k for k in live.keys() | expected.keys() if live.get(k) != expected.get(k))}")
    aliases = ingress["aliases"]
    if len(set(aliases.values())) != len(aliases) or any(old in units or key not in units for old, key in aliases.items()):
        raise ValueError("ambiguous HealthKit aliases")
    for key, variants in ingress["unit_rules"].items():
        for unit, rule in variants.items():
            factors = [rule[name] for name in ("multiplier", "divisor") if name in rule]
            if rule["unit"] != units.get(key) or unit == rule["unit"] or len(factors) != 1 or factors[0] <= 0:
                raise ValueError(f"invalid HealthKit unit rule: {key}/{unit}")


def validate(catalog, swift):
    rows = catalog["observations"]
    ingress = catalog["healthkit_ingress"]
    validate_ingress(ingress, rows)
    evidence = observation_evidence(swift, ingress)
    changed = sorted(key for key in rows.keys() | evidence.keys() if rows.get(key) != evidence.get(key))
    if changed:
        raise ValueError("source inventory drift: " + ", ".join(changed))
    for name, family in catalog["families"].items():
        if "go_type" in family:
            actual = go_fields(family["owner"], family["go_type"])
            accounted = {f["field"] for f in family["fields"].values()} | set(family["ignored_fields"])
            if actual != accounted:
                raise ValueError(f"{name}: unmapped/obsolete DTO fields {actual ^ accounted}")
    items = list(definitions(catalog))
    indices = {item["metric_id"]:item for item in items}
    for key, binding in catalog["dbt_bindings"].items():
        if key not in indices or not binding.get("model") or not binding.get("columns"):
            raise ValueError(f"invalid dbt binding: {key}")
    if len(indices) != len(items):
        raise ValueError("duplicate metric id")
    for item in items:
        for prop in ("version","value_type","units","method","grain","clock","parents","quality","coverage","owner","consumers","status","reduction","source_keys"):
            if prop not in item or item[prop] is None or item[prop] == "":
                raise ValueError(f"{item['metric_id']}: missing {prop}")
        if not set(item["units"]).issubset(catalog["units"]):
            raise ValueError(f"undeclared unit in {item['metric_id']}")
        if unknown := set(item["parents"]) - indices.keys():
            raise ValueError(f"{item['metric_id']}: undefined parents {unknown}")
        if not isinstance(item["version"], int) or item["version"] < 1:
            raise ValueError(f"{item['metric_id']}: invalid definition version")
        if not item["units"] or not item["consumers"]:
            raise ValueError(f"{item['metric_id']}: units and consumers require a value or explicit unknown")
        if not (ROOT / item["owner"]).is_file():
            raise ValueError(f"{item['metric_id']}: missing source {item['owner']}")
    active = set()
    visited = set()

    def visit(key):
        if key in active:
            raise ValueError(f"cyclic parent reference from {key}")
        if key not in visited:
            active.add(key)
            for parent in indices[key]["parents"]:
                visit(parent)
            active.remove(key)
            visited.add(key)
    for key in indices:
        visit(key)
    return items


def compare_inventory(catalog, path):
    counts = Counter()
    details = []
    for row in json.loads(path.read_text()):
        key, unit, rows = row["metric_name"], row["units"], row["rows"]
        if type(rows) is not int or rows < 0:
            raise ValueError("inventory requires nonnegative integer row counts")
        known = catalog["observations"].get(key)
        if known is None:
            status = "unclassified"
        elif unit in source_units(known):
            status = "declared_unit"
        else:
            status = "unit_needs_review"
        counts[status] += rows
        details.append(dict(metric_name=key, units=unit, rows=rows, status=status))
    return {"row_counts":dict(counts), "entries":details}


def read_catalog():
    properties = json.loads(CATALOG.read_text(), object_pairs_hook=unique_pairs)
    model = next(m for m in properties["models"] if m["name"] == "semantic_metric_catalog_v1")
    return model["config"]["meta"]["health_catalog"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--swift", type=Path, default=SWIFT)
    parser.add_argument("--inventory", type=Path, help="aggregate JSON with metric_name, units, rows only")
    parser.add_argument("--write-swift-ingress", type=Path, help="generate the Swift ingress definitions from the catalog")
    parser.add_argument("--expand", action="store_true", help="emit resolved definitions")
    args = parser.parse_args()
    catalog = read_catalog()
    if args.write_swift_ingress:
        ingress = catalog["healthkit_ingress"]
        validate_ingress(ingress, catalog["observations"])
        args.write_swift_ingress.write_text(swift_ingress_source(ingress))
        return
    items = validate(catalog, args.swift)
    if args.expand:
        print(json.dumps(items, ensure_ascii=False, indent=2))
    elif args.inventory:
        print(json.dumps(compare_inventory(catalog,args.inventory), ensure_ascii=False))
    else:
        print(f"{len(catalog['observations'])} observations, {len(catalog['families'])} families, "
              f"{len(catalog['contracts'])} named contracts, {len(items)} unique definitions")


if __name__ == "__main__":
    main()
