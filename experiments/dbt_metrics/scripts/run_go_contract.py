#!/usr/bin/env python3
"""Characterize both real Go aggregate paths in an owned synthetic database.

Run --record before a refactor, then --compare after it. The baseline lives in
ignored artifacts and is never regenerated by compare. No DATABASE_URL is used.
"""
import argparse
import json
import os
from pathlib import Path
import time

import run_pilot as p

BASELINE = p.HERE / "artifacts/go-contract-before.json"
RESULT = p.HERE / "artifacts/go-contract-after.json"


def characterize(cid, dsn):
    dates = [f"2026-01-{i:02d}" for i in range(1, 16)]
    result = {}
    modes = ("live", "legacy-force", "legacy-incremental", "legacy-date")
    for mode in modes:
        p.require_owned(cid, p.TOKEN)
        p.load_sql(cid, "TRUNCATE source_data.metric_points, source_data.calendar, go_oracle.hourly_metrics, go_oracle.daily_scores;")
        p.load_sql(cid, (p.HERE / "fixtures/base.sql").read_text())
        # Unequal source hours: live HRV=25, legacy HRV=20. Unknown sleep:
        # live sums 2+4, legacy averages them. Unknown ordinary remains AVG.
        p.load_sql(cid, """
INSERT INTO source_data.metric_points VALUES
('heart_rate_variability','2026-01-15 10:01:00','Contract A',10,'ok'),
('heart_rate_variability','2026-01-15 11:01:00','Contract A',10,'ok'),
('heart_rate_variability','2026-01-15 10:01:00','Contract B',40,'ok'),
('sleep_unknown','2026-01-15 10:01:00','Contract A',2,'ok'),
('sleep_unknown','2026-01-15 10:02:00','Contract A',4,'ok'),
('unknown_metric','2026-01-15 10:01:00','Contract A',2,'ok'),
('unknown_metric','2026-01-15 10:02:00','Contract A',4,'ok');
""")
        os.environ["DBT_PILOT_GO_MODE"] = mode
        output = p.HERE / "artifacts/go-contract-current.json"

        def snapshot(label, reset=False):
            p.require_owned(cid, p.TOKEN)
            observed = p.run_go(dsn, p.TOKEN, dates, output, reset)
            observed.pop("seconds")
            if mode == "legacy-date":
                p.assert_same_outputs(observed, result[f"legacy-force/{label}"], "bounded legacy date " + label)
            else:
                result[f"{mode}/{label}"] = observed
            return observed

        first = snapshot("initial", True)
        day = next(row for row in first["daily"] if row["date"] == "2026-01-15")
        assert day["hrv_avg"] == (25 if mode == "live" else 20), day
        unknown = next(row for row in first["hourly"] if row["metric_name"] == "sleep_unknown")
        assert unknown["avg_val"] == (6 if mode == "live" else 3), unknown
        ordinary = next(row for row in first["hourly"] if row["metric_name"] == "unknown_metric")
        assert ordinary["avg_val"] == 3, ordinary
        repeated = snapshot("repeat")
        p.assert_same_outputs(repeated, first, mode + " repeat")
        # Changes inside legacy's refresh window, also meaningful for force.
        p.load_sql(cid, """
UPDATE source_data.metric_points SET quality='invalid' WHERE metric_name='heart_rate_variability' AND SUBSTRING(date,1,10)='2026-01-15' AND source='Contract B';
INSERT INTO source_data.metric_points VALUES ('unknown_metric','2026-01-14 10:01:00','Contract A',7,'ok');
""")
        mutated = snapshot("invalid-and-late")
        p.assert_untouched(first, mutated, {"2026-01-14", "2026-01-15"}, mode)
        # A clean rebuild captures the existing stale-hour versus rebuild split.
        snapshot("fresh-rebuild", True)
    os.environ.pop("DBT_PILOT_GO_MODE", None)
    return result


def main():
    parser = argparse.ArgumentParser()
    choice = parser.add_mutually_exclusive_group(required=True)
    choice.add_argument("--record", action="store_true")
    choice.add_argument("--compare", action="store_true")
    args = parser.parse_args()
    if args.record and BASELINE.exists():
        raise RuntimeError("baseline already exists; refusing to overwrite")
    expected = json.loads(BASELINE.read_text()) if args.compare else None
    p.docker("run", "-d", "--name", p.NAME, "--label", f"codex.health-dbt-pilot={p.TOKEN}",
             "-e", "POSTGRES_USER=pilot_admin", "-e", f"POSTGRES_PASSWORD={p.PASSWORD}",
             "-e", f"POSTGRES_DB={p.DB}", "-p", "127.0.0.1::5432", p.IMAGE)
    cid = p.docker("inspect", "-f", "{{.Id}}", p.NAME, capture=True).stdout.strip()
    try:
        for _ in range(60):
            if p.docker("exec", cid, "pg_isready", "-U", "pilot_admin", "-d", p.DB, capture=True, check=False).returncode == 0:
                break
            time.sleep(1)
        else:
            raise RuntimeError("synthetic database did not become ready")
        port = p.docker("port", cid, "5432/tcp", capture=True).stdout.strip()
        if not port.startswith("127.0.0.1:"):
            raise RuntimeError("loopback port required")
        p.load_sql(cid, f"CREATE TABLE public.pilot_identity(token text NOT NULL); INSERT INTO public.pilot_identity VALUES ('{p.TOKEN}');")
        p.require_owned(cid, p.TOKEN)
        p.load_sql(cid, (p.HERE / "fixtures/schema.sql").read_text())
        BASELINE.parent.mkdir(parents=True, exist_ok=True)
        dsn = f"postgres://pilot_admin:{p.PASSWORD}@{port}/{p.DB}?sslmode=disable"
        observed = characterize(cid, dsn)
        if expected is not None:
            if observed.keys() != expected.keys():
                raise RuntimeError("scenario set changed")
            for name in expected:
                p.assert_same_outputs(observed[name], expected[name], name)
                for field in ("hourly", "daily", "sum_metrics"):
                    if observed[name][field] != expected[name][field]:
                        raise RuntimeError(f"{name}: {field} differs from exact baseline")
        (RESULT if args.compare else BASELINE).write_text(json.dumps(observed, indent=2))
        print(f"PASS: {len(observed)} Go snapshots {'match baseline' if args.compare else 'recorded'}")
    finally:
        p.require_owned(cid, p.TOKEN)
        p.docker("rm", "-f", "-v", cid)
        if p.docker("inspect", cid, capture=True, check=False).returncode == 0:
            raise RuntimeError("owned container cleanup failed")
        print("PASS: owned container and volume removed")


if __name__ == "__main__":
    main()
