export type PageMessageKey = keyof (typeof pageMessages)["en"];

export function tp(
  locale: Locale,
  key: PageMessageKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = pageMessages[locale][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
